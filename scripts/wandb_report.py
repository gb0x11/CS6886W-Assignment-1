"""Create the W&B report holding the Question 3 panels (requires `wandb login`).

    pip install wandb-workspaces
    python scripts/wandb_report.py [--entity ENTITY] [--project PROJECT] [--url EXISTING_REPORT]

Panels (all generated by W&B from the logged runs):
  * parallel-coordinates plot of the hyper-parameters vs. best validation accuracy
  * validation accuracy vs. run creation time (scatter, with running max)
  * training loss / training accuracy / validation loss / validation accuracy vs. epoch
  * parameter importance with respect to val_acc
"""
import argparse

import wandb
import wandb_workspaces.reports.v2 as wr


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--entity", default=None, help="defaults to your W&B default entity")
    p.add_argument("--project", default="cs6886w-vgg6-cifar10")
    p.add_argument("--url", help="update this existing report instead of creating a new one")
    args = p.parse_args()
    entity = args.entity or wandb.Api().default_entity

    runset = wr.Runset(entity=entity, project=args.project, name="All runs")
    hp = ["activation", "batch_norm", "batch_size", "epochs", "lr", "momentum",
          "optimizer", "weight_decay"]
    parallel = wr.ParallelCoordinatesPlot(
        title="Configuration vs. validation accuracy",
        columns=[wr.ParallelCoordinatesPlotColumn(metric=wr.Config(h), log=h in ("lr",))
                 for h in hp] + [wr.ParallelCoordinatesPlotColumn(metric=wr.SummaryMetric("best_val_acc"),
                                                                    display_name="val_acc")],
        layout=wr.Layout(x=0, y=0, w=24, h=10))
    scatter = wr.ScatterPlot(title="val_acc v. created", x=wr.Metric("CreatedTimestamp"),
                             y=wr.SummaryMetric("best_val_acc"), running_ymax=True,
                             layout=wr.Layout(x=0, y=10, w=24, h=8))
    lines = [wr.LinePlot(title=m, x="epoch", y=[m], max_runs_to_show=100,
                         layout=wr.Layout(x=12 * (i % 2), y=18 + 8 * (i // 2), w=12, h=8))
             for i, m in enumerate(["train_acc", "train_loss", "val_acc", "val_loss"])]
    importance = wr.ParameterImportancePlot(with_respect_to="best_val_acc",
                                            layout=wr.Layout(x=0, y=34, w=24, h=9))

    report = wr.Report.from_url(args.url) if args.url else wr.Report(entity=entity, project=args.project)
    report_fields = dict(
        title="CS6886W A1: VGG6 on CIFAR-10 (Question 3 plots)",
        description="Parallel coordinates, val_acc vs. created, and train/val loss & accuracy "
                    "for every configuration explored.",
        blocks=[
            wr.H1("VGG6 on CIFAR-10: configuration study"),
            wr.P("Every run trains VGG6 (0.26M params) on 45k CIFAR-10 images and validates on a "
                 "held-out 5k split. The summary metric best_val_acc is the best validation accuracy "
                 "of the run (shown as val_acc in the parallel-coordinates plot)."),
            wr.PanelGrid(runsets=[runset], panels=[parallel, scatter, *lines, importance]),
        ],
        width="fluid",
    )
    for k, v in report_fields.items():
        setattr(report, k, v)
    report.save()
    print(report.url)


if __name__ == "__main__":
    main()
